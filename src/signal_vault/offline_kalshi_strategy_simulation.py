"""Historical one-contract simulation for frozen Kalshi reference hypotheses.

The entry decision is generated by Phase 57 using only the pre-settlement trade
price. Only AFTER that decision is fixed does this module consult the known
settlement outcome to score a one-contract hold-to-settlement result.

Entry references are deliberately conservative but still hypothetical:
- BUY YES uses same-candle historical YES ask close.
- BUY NO uses 1 - same-candle historical YES bid close.
- fixed extra entry-friction scenarios are added on top.
No historical depth, queue priority, real fee schedule, or actual fill is
claimed. No provider or order capability exists here.
"""
from __future__ import annotations

import hashlib
import json
from decimal import Decimal, InvalidOperation
from pathlib import Path
from typing import Mapping

from .kalshi_reference_hypotheses import HYPOTHESES, reference_decision
from .offline_kalshi_resolved_validation import (
    MAX_FILE_BYTES,
    _read_json,
    score_resolved_market_evidence,
)

FRICTION_SCENARIOS={
    "illustrative_low_extra_entry_friction":Decimal("0.00"),
    "illustrative_base_extra_entry_friction":Decimal("0.01"),
    "illustrative_high_extra_entry_friction":Decimal("0.03"),
}


def _price(raw:object, *, name:str)->Decimal:
    if not isinstance(raw,str) or len(raw)>32:
        raise ValueError(f"Kalshi {name} must be a dollar string")
    try:
        value=Decimal(raw)
    except (InvalidOperation,ValueError) as exc:
        raise ValueError(f"invalid Kalshi {name}") from exc
    if not value.is_finite() or value<0 or value>1:
        raise ValueError(f"Kalshi {name} outside 0..1")
    return value


def _quote_close(candle:Mapping[str,object], key:str)->Decimal:
    obj=candle.get(key)
    if not isinstance(obj,Mapping):
        raise ValueError(f"Kalshi candle missing {key} quote")
    return _price(obj.get("close"),name=f"{key}.close")


def simulate_resolved_market_references(
    source_root:str|Path,
)->dict[str,object]:
    root=Path(source_root)
    scored=score_resolved_market_evidence(root)
    manifest,manifest_raw=_read_json(root/"manifest.json")
    candles,candle_raw=_read_json(root/"candlesticks.json")
    if hashlib.sha256(candle_raw).hexdigest()!=manifest.get("candlesticks_sha256"):
        raise ValueError("Kalshi candle SHA changed before strategy simulation")
    rows=candles.get("candlesticks")
    if not isinstance(rows,list):
        raise ValueError("Kalshi historical candle rows missing")
    by_end={}
    for candle in rows:
        if not isinstance(candle,Mapping):
            raise ValueError("malformed Kalshi historical candle")
        at=candle.get("end_period_ts")
        if type(at) is not int or at in by_end:
            raise ValueError("duplicate/invalid Kalshi candle endpoint")
        by_end[at]=candle

    horizon_rows={
        row["horizon_seconds_before_settlement"]:row
        for row in scored["fixed_horizon_scores"]
    }
    result=scored["resolved_result"]
    simulations={}
    for scenario,extra_friction in FRICTION_SCENARIOS.items():
        hypothesis_results={}
        for hypothesis in HYPOTHESES:
            if hypothesis.entry_horizon_seconds is None:
                decision=reference_decision(
                    hypothesis,yes_trade_probability=None
                )
                hypothesis_results[hypothesis.name]={
                    "decision":decision,
                    "entry_reference":"NONE",
                    "extra_entry_friction_dollars":str(extra_friction),
                    "hypothetical_contract_count":0,
                    "hypothetical_pnl_dollars":"0",
                    "entry_blocked":False,
                }
                continue

            horizon=horizon_rows.get(hypothesis.entry_horizon_seconds)
            if not isinstance(horizon,Mapping):
                raise ValueError("frozen Kalshi strategy horizon missing from source score")
            if horizon.get("observation_available") is not True:
                decision=reference_decision(
                    hypothesis,yes_trade_probability=None
                )
                hypothesis_results[hypothesis.name]={
                    "decision":decision,
                    "entry_reference":"UNAVAILABLE",
                    "extra_entry_friction_dollars":str(extra_friction),
                    "hypothetical_contract_count":0,
                    "hypothetical_pnl_dollars":"0",
                    "entry_blocked":True,
                    "entry_block_reason":"NO_PRESETTLEMENT_CANDLE_AT_FIXED_HORIZON",
                }
                continue

            p=_price(
                horizon.get("yes_probability"),
                name="historical YES trade close",
            )
            decision=reference_decision(
                hypothesis,yes_trade_probability=p
            )
            action=decision["action"]
            if action=="hold":
                hypothesis_results[hypothesis.name]={
                    "decision":decision,
                    "entry_reference":"NONE",
                    "extra_entry_friction_dollars":str(extra_friction),
                    "hypothetical_contract_count":0,
                    "hypothetical_pnl_dollars":"0",
                    "entry_blocked":False,
                }
                continue

            candle=by_end.get(horizon.get("candle_end_ts"))
            if not isinstance(candle,Mapping):
                raise ValueError("fixed-horizon candle cannot be recovered")
            yes_bid=_quote_close(candle,"yes_bid")
            yes_ask=_quote_close(candle,"yes_ask")
            if yes_bid>yes_ask:
                raise ValueError("Kalshi historical YES bid exceeds ask")

            if action=="buy_yes":
                reference=yes_ask
                payout=Decimal(1) if result=="yes" else Decimal(0)
                reference_kind="YES_ASK_CLOSE"
            elif action=="buy_no":
                reference=Decimal(1)-yes_bid
                payout=Decimal(1) if result=="no" else Decimal(0)
                reference_kind="ONE_MINUS_YES_BID_CLOSE"
            else:
                raise ValueError("unknown frozen Kalshi reference action")
            total_cost=reference+extra_friction
            if total_cost<=0 or total_cost>=1:
                hypothesis_results[hypothesis.name]={
                    "decision":decision,
                    "entry_reference":reference_kind,
                    "quoted_entry_cost_dollars":str(reference),
                    "extra_entry_friction_dollars":str(extra_friction),
                    "hypothetical_contract_count":0,
                    "hypothetical_pnl_dollars":"0",
                    "entry_blocked":True,
                    "entry_block_reason":"CONSERVATIVE_TOTAL_COST_NOT_INSIDE_0_1",
                }
                continue
            pnl=payout-total_cost
            hypothesis_results[hypothesis.name]={
                "decision":decision,
                "entry_reference":reference_kind,
                "quoted_entry_cost_dollars":str(reference),
                "extra_entry_friction_dollars":str(extra_friction),
                "total_hypothetical_entry_cost_dollars":str(total_cost),
                "settlement_payout_dollars":str(payout),
                "hypothetical_contract_count":1,
                "hypothetical_pnl_dollars":str(pnl),
                "entry_blocked":False,
            }
        simulations[scenario]={
            "extra_entry_friction_dollars":str(extra_friction),
            "friction_is_illustrative_not_provider_fee_schedule":True,
            "hypotheses":hypothesis_results,
        }

    return {
        "kind":"OFFLINE_KALSHI_FROZEN_REFERENCE_STRATEGY_SIMULATION",
        "ticker":scored["ticker"],
        "resolved_result":result,
        "settlement_ts":scored["settlement_ts"],
        "source_manifest_sha256":
            hashlib.sha256(manifest_raw).hexdigest(),
        "fixed_hypotheses":[x.name for x in HYPOTHESES],
        "friction_scenarios":simulations,
        "decision_made_before_outcome_scoring":True,
        "historical_quote_close_is_not_guaranteed_fill":True,
        "historical_orderbook_depth_reconstructed":False,
        "provider_fee_schedule_modeled":False,
        "strategy_selection_performed":False,
        "automatic_strategy_promotion":"DISABLED",
        "credentials_accessed":"NONE",
        "network_requests":"NONE",
        "demo_order_submission":"DISABLED",
        "live_order_submission":"DISABLED",
        "live_trading":"UNAVAILABLE",
    }
